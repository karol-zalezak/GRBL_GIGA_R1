// Fourth axis. None of the upstream machine profiles above has one, so A gets
// its defaults here unless a profile defines them. With the default $42=0 the
// A axis is rotary and these are in degrees: 1/16 microstepping on a 200 step
// motor through a 1:1 drive is 3200 steps per turn = 8.889 steps/degree.
#ifndef DEFAULT_A_STEPS_PER_MM
  #define DEFAULT_A_STEPS_PER_MM 8.888889   // steps/deg (rotary) or steps/mm (linear)
#endif
#ifndef DEFAULT_A_MAX_RATE
  #define DEFAULT_A_MAX_RATE 3600.0         // deg/min (10 rev/min)
#endif
#ifndef DEFAULT_A_ACCELERATION
  #define DEFAULT_A_ACCELERATION (360.0*60*60) // 360 deg/sec^2
#endif
#ifndef DEFAULT_A_MAX_TRAVEL
  #define DEFAULT_A_MAX_TRAVEL 360.0        // deg; only used for soft limits on a homed A
#endif

// $42: what the A motor is. 0 = independent rotary axis (degrees), 1 = independent
// linear axis (mm), 2 = second motor of X, 3 = second motor of Y. See kinematics.h.
#ifndef DEFAULT_A_MODE
  #define DEFAULT_A_MODE 0
#endif
// $43: home an independent A axis as the last cycle of $H. Off by default, since
// a rotary table often has no home switch.
#ifndef DEFAULT_A_HOMING
  #define DEFAULT_A_HOMING 0
#endif
// $46: aux outputs (bit 0 = AUX0 ... bit 5 = AUX5) that switch on together
// with the spindle - AUX0 is meant for the dust extraction.
#ifndef DEFAULT_AUX_FOLLOW_SPINDLE
  #define DEFAULT_AUX_FOLLOW_SPINDLE 1
#endif

// The upstream profiles above still define DEFAULT_INVERT_LIMIT_PINS and
// DEFAULT_INVERT_PROBE_PIN; this port ignores them. Every input has its own
// NC bit in $79 instead (DEFAULT_IN_INVERT).

// $48-$50: Z brake timing, ms. Unknown until measured on the machine, so the
// defaults err on the long side: a step into a brake that has not let go yet
// costs steps, waiting 300 ms costs nothing.
#ifndef DEFAULT_BRAKE_ON_MS
  #define DEFAULT_BRAKE_ON_MS 200       // drivers enabled -> brake released
#endif
#ifndef DEFAULT_BRAKE_RELEASE_MS
  #define DEFAULT_BRAKE_RELEASE_MS 100  // brake released -> first step
#endif
#ifndef DEFAULT_BRAKE_OFF_MS
  #define DEFAULT_BRAKE_OFF_MS 200      // brake engaged -> drivers disabled
#endif
// $59: who works the brake. 1 = the BRAKE output (D16) with the times above,
// 0 = the drive itself (Delta BRKR, Nanotec C5 output 1); BRAKE stays off.
#ifndef DEFAULT_BRAKE_MODE
  #define DEFAULT_BRAKE_MODE 1
#endif
// $51: spindle run-down, ms. The collet may open only after the spindle has
// been off this long.
#ifndef DEFAULT_SPINDLE_RUNDOWN_MS
  #define DEFAULT_SPINDLE_RUNDOWN_MS 5000
#endif
// $52-$54: spindle at-speed. With $52=0 Grbl does not wait for the at-speed
// input (a bare board has none) and waits the fixed $54 instead.
#ifndef DEFAULT_AT_SPEED_TIMEOUT_MS
  #define DEFAULT_AT_SPEED_TIMEOUT_MS 0
#endif
#ifndef DEFAULT_AT_SPEED_LOSS
  #define DEFAULT_AT_SPEED_LOSS 2       // 0 ignore, 1 feed hold, 2 alarm
#endif
#ifndef DEFAULT_SPINUP_DELAY_MS
  #define DEFAULT_SPINUP_DELAY_MS 0
#endif
// $55: length of the servo / VFD reset pulse, ms.
#ifndef DEFAULT_RESET_PULSE_MS
  #define DEFAULT_RESET_PULSE_MS 500
#endif
// $56: delay between a direction change and the next step, us. 0 as upstream;
// a Nanotec C5 needs 35.
#ifndef DEFAULT_DIR_DELAY_US
  #define DEFAULT_DIR_DELAY_US 0
#endif
// $57: central STOP input in use. Off until the safety relay is wired.
#ifndef DEFAULT_ESTOP_ENABLE
  #define DEFAULT_ESTOP_ENABLE 0
#endif
// $94: driver power input (D53) watched. Off until the shield senses the supply.
#ifndef DEFAULT_DRV_POWER_ENABLE
  #define DEFAULT_DRV_POWER_ENABLE 0
#endif
// $95: the supply must be back this long before $H/$X are accepted, ms (drives
// boot; servo drives take a second or two).
#ifndef DEFAULT_DRV_POWER_DELAY_MS
  #define DEFAULT_DRV_POWER_DELAY_MS 1000
#endif
// $96-$98: handwheel. Off until a pendant is wired; 1 um per detent at x1.
