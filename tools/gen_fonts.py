#!/usr/bin/env python3
"""
gen_fonts.py - renders the display fonts into src/m4/fonts.h

Part of Grbl-Giga. Run with any Python 3 that has Pillow:

    python tools/gen_fonts.py

The fonts are DejaVu Sans Mono (Bitstream Vera licence, free to embed),
taken from matplotlib's copy unless --ttf-dir points elsewhere. Every glyph
is rendered into a fixed cell with 16 levels of anti-aliasing (4 bits per
pixel, two pixels per byte, high nibble first), which the M4 blends between
foreground and background colour while drawing. Monospaced cells keep the
layout code trivial: a string of n characters is n * advance pixels wide.

The degree sign is stored at code 127, which is where the display code
asks for it.
"""

import argparse
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ASCII = ''.join(chr(c) for c in range(32, 127)) + '°'

# name, file, pixel size, characters
FONTS = [
    ('dro',   'DejaVuSansMono-Bold.ttf', 60, ' +-.0123456789XYZA°'),
    ('big',   'DejaVuSansMono-Bold.ttf', 34, ASCII),
    ('med',   'DejaVuSansMono-Bold.ttf', 21, ASCII),
    ('small', 'DejaVuSansMono.ttf',      16, ASCII),
]


def find_ttf_dir():
    try:
        import matplotlib
        d = os.path.join(os.path.dirname(matplotlib.__file__), 'mpl-data', 'fonts', 'ttf')
        if os.path.isdir(d):
            return d
    except ImportError:
        pass
    return None


def render(name, path, size, chars):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    adv = int(round(font.getlength('0')))
    h_full = ascent + descent
    imgs = []
    for ch in chars:
        im = Image.new('L', (adv, h_full), 0)
        ImageDraw.Draw(im).text((0, 0), ch, font=font, fill=255)
        imgs.append(im)
    # Crop rows that no glyph of this set uses, so a digits-only font is no
    # taller than its digits.
    top, bottom = h_full, 0
    for im in imgs:
        bb = im.getbbox()
        if bb:
            top = min(top, bb[1])
            bottom = max(bottom, bb[3])
    if top >= bottom:
        top, bottom = 0, h_full
    # Keep the baseline area for fonts that carry lower case.
    if any(c in chars for c in 'gjpqy'):
        bottom = h_full
    h = bottom - top
    data = bytearray()
    for im in imgs:
        im = im.crop((0, top, adv, bottom))
        px = im.load()
        for y in range(h):
            row = []
            for x in range(adv):
                row.append((px[x, y] * 15 + 127) // 255)
            if len(row) % 2:
                row.append(0)
            for i in range(0, len(row), 2):
                data.append((row[i] << 4) | row[i + 1])
    return adv, h, data


def c_string(chars):
    out = ''
    for ch in chars:
        if ch == '°':
            out += '\\x7f'
        elif ch in '\\"':
            out += '\\' + ch
        else:
            out += ch
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ttf-dir', default=None)
    ap.add_argument('--out', default=os.path.join(os.path.dirname(__file__), '..', 'src', 'm4', 'fonts.h'))
    args = ap.parse_args()
    ttf_dir = args.ttf_dir or find_ttf_dir()
    if not ttf_dir:
        sys.exit('DejaVu fonts not found; install matplotlib or pass --ttf-dir')

    lines = [
        '// fonts.h - generated by tools/gen_fonts.py, do not edit.',
        '// DejaVu Sans Mono, Bitstream Vera licence (free to embed and redistribute).',
        '// 4 bits per pixel, two pixels per byte (high nibble first), rows padded to a byte.',
        '#ifndef fonts_h',
        '#define fonts_h',
        '#include <stdint.h>',
        '',
        'typedef struct {',
        '  const uint8_t *bitmap;   // glyph cells, in the order of map',
        '  const char *map;         // characters present; the degree sign is \\x7f',
        '  uint8_t adv;             // cell width = advance',
        '  uint8_t h;               // cell height',
        '  uint16_t stride;         // bytes per glyph',
        '} font_t;',
        '',
    ]
    total = 0
    for name, fname, size, chars in FONTS:
        adv, h, data = render(name, os.path.join(ttf_dir, fname), size, chars)
        stride = ((adv + 1) // 2) * h
        total += len(data)
        lines.append('// %s: %s %d px, cell %dx%d, %d glyphs, %d bytes' % (name, fname, size, adv, h, len(chars), len(data)))
        lines.append('static const uint8_t font_%s_bitmap[%d] = {' % (name, len(data)))
        for i in range(0, len(data), 24):
            lines.append('  ' + ','.join('0x%02x' % b for b in data[i:i + 24]) + ',')
        lines.append('};')
        lines.append('static const font_t font_%s = { font_%s_bitmap, "%s", %d, %d, %d };' %
                     (name, name, c_string(chars), adv, h, stride))
        lines.append('')
    lines.append('#endif')
    with open(args.out, 'w', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print('wrote %s (%d bytes of glyphs)' % (args.out, total))


if __name__ == '__main__':
    main()
