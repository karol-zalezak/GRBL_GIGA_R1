#!/usr/bin/env python3
"""
make_logo.py - turns the Grbl logo (SVG) into a bitmap for the display

Part of Grbl-Giga. Reads the filled paths of docs/Grbl Logo.svg, flattens
their curves, rasterizes them with 4 x 4 subsamples per pixel (non-zero
winding, as SVG fills) and writes src/m4/logo.h: 4-bit coverage, two pixels
a byte (high nibble first), rows of (w + 1) / 2 bytes - the format of the
display's fonts, so canvas.cpp draws it the same way, in any colour.

    python tools/make_logo.py [width]        (default 240 px wide)

Only what that SVG uses is understood: path commands M m L l C c Z z.
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
SRC = os.path.join(ROOT, 'docs', 'Grbl Logo.svg')
OUT = os.path.join(ROOT, 'src', 'm4', 'logo.h')
SUB = 4                 # subsamples per pixel, each way
CURVE_STEPS = 24        # line segments per cubic


def tokens(d):
    return re.findall(r'[MmLlCcZz]|[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?', d)


def path_polygons(d):
    """Flattens one path's data into closed polygons (lists of points)."""
    t = tokens(d)
    i = 0
    polys, cur = [], []
    x = y = sx = sy = 0.0
    cmd = None
    while i < len(t):
        if t[i] in 'MmLlCcZz':
            cmd = t[i]
            i += 1
            if cmd in 'Zz':
                if cur:
                    polys.append(cur)
                cur = []
                x, y = sx, sy
                continue
        nums = lambda n: [float(v) for v in t[i:i + n]]
        if cmd in 'Mm':
            dx, dy = nums(2); i += 2
            if cmd == 'm':
                dx += x; dy += y
            if cur:
                polys.append(cur)
            x, y = sx, sy = dx, dy
            cur = [(x, y)]
            cmd = 'l' if cmd == 'm' else 'L'     # further pairs are line-tos
        elif cmd in 'Ll':
            dx, dy = nums(2); i += 2
            x, y = (x + dx, y + dy) if cmd == 'l' else (dx, dy)
            cur.append((x, y))
        elif cmd in 'Cc':
            v = nums(6); i += 6
            if cmd == 'c':
                v = [v[0] + x, v[1] + y, v[2] + x, v[3] + y, v[4] + x, v[5] + y]
            x0, y0 = x, y
            for k in range(1, CURVE_STEPS + 1):
                s = k / CURVE_STEPS
                a, b, c, e = (1 - s) ** 3, 3 * s * (1 - s) ** 2, 3 * s * s * (1 - s), s ** 3
                cur.append((a * x0 + b * v[0] + c * v[2] + e * v[4], a * y0 + b * v[1] + c * v[3] + e * v[5]))
            x, y = v[4], v[5]
        else:
            raise ValueError('unexpected token %r' % t[i])
    if cur:
        polys.append(cur)
    return polys


def main():
    width = int(sys.argv[1]) if len(sys.argv) > 1 else 240
    svg = open(SRC, encoding='utf-8').read()
    svg = svg[svg.find('</defs>'):]              # markers and hatches up there draw nothing
    polys = []
    for m in re.finditer(r'<path\b([^>]*)>', svg, re.S):
        attrs = m.group(1)
        if 'fill:none' in attrs.replace(' ', ''):
            continue                              # the lone stroke: no area
        d = re.search(r'\sd="([^"]+)"', attrs).group(1)
        polys += path_polygons(d)
    xs = [p[0] for poly in polys for p in poly]
    ys = [p[1] for poly in polys for p in poly]
    x0, y0, bw, bh = min(xs), min(ys), max(xs) - min(xs), max(ys) - min(ys)
    scale = (width - 1) / bw
    height = int(bh * scale) + 2
    ox, oy = 0.5, (height - bh * scale) / 2.0

    # Edges in subsample space, with their direction for the winding count.
    edges = []
    for poly in polys:
        pts = [((px - x0) * scale + ox, (py - y0) * scale + oy) for px, py in poly]
        for k in range(len(pts)):
            (ax, ay), (bx, by) = pts[k], pts[(k + 1) % len(pts)]
            if ay != by:
                edges.append((ax * SUB, ay * SUB, bx * SUB, by * SUB))
    cover = [[0] * width for _ in range(height)]
    for sy in range(height * SUB):
        yc = sy + 0.5
        xings = []
        for ax, ay, bx, by in edges:
            if (ay <= yc < by) or (by <= yc < ay):
                xings.append((ax + (yc - ay) * (bx - ax) / (by - ay), 1 if by > ay else -1))
        xings.sort()
        wind = 0
        for k in range(len(xings) - 1):
            wind += xings[k][1]
            if wind == 0:
                continue
            for sx in range(max(0, int(xings[k][0] + 0.5)), min(width * SUB, int(xings[k + 1][0] + 0.5))):
                cover[sy // SUB][sx // SUB] += 1
    rows = []
    for y in range(height):
        a = [min(15, (c * 15 + 8) // (SUB * SUB)) for c in cover[y]]
        if len(a) % 2:
            a.append(0)
        rows.append(bytes((a[k] << 4) | a[k + 1] for k in range(0, len(a), 2)))

    lines = ['// Generated by tools/make_logo.py from docs/Grbl Logo.svg - do not edit.',
             '// The Grbl logo, %d x %d: 4-bit coverage, two pixels a byte (high nibble' % (width, height),
             '// first), rows of (LOGO_W + 1) / 2 bytes - the fonts\' format (cv_bitmap4).',
             '#ifndef logo_h', '#define logo_h', '',
             '#define LOGO_W  %d' % width, '#define LOGO_H  %d' % height, '',
             'static const uint8_t logo_bitmap[] = {']
    for r in rows:
        lines.append('  ' + ', '.join('0x%02X' % b for b in r) + ',')
    lines += ['};', '', '#endif', '']
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
    print('wrote %s: %d x %d, %d bytes' % (os.path.relpath(OUT, ROOT), width, height, sum(len(r) for r in rows)))
    for y in range(0, height, max(1, height // 30)):          # a rough preview
        print(''.join(' .:-=+*#%@@@@@@@'[min(15, c * 15 // 16)] for c in cover[y][::max(1, width // 100)]))


if __name__ == '__main__':
    main()
